    s = re.sub(r'\s*-\s*باكو كبير', '', s)
    s = re.sub(r'\s*\((باكو فردي|كيس فردي|ظرف فردي|قطعة فردية|علبة فردية|زجاجة فردية|كوب فردي|دفتر فردي|قالب فردي)\)', '', s)
    s = re.sub(r'\s+(عبوة فردية|قطعة فردية|باكو فردي|علبة فردية|كوب فردي|كيس فردي|ظرف فردي|زجاجة فردية|علبة صفيح فردية|زجاجة بلاستيك فردية|قالب فردي|قالب كبير)', '', s)
    s = re.sub(r'\s*عبوة التوفير\s*', ' توفير ', s)

    # 2. Coffee brand cleanups
    s = re.sub(r'^قهوة سريعة التحضير نسكافيه\b', 'نسكافيه', s)
    s = re.sub(r'^قهوة سريعة التحضير علي كافيه\b', 'علي كافيه', s)
    s = re.sub(r'^قهوة سريعة التحضير كوفي بريك\b', 'كوفي بريك', s)
    s = re.sub(r'^قهوة سريعة التحضير بونجورنو\b', 'بونجورنو', s)
    s = re.sub(r'^قهوة سريعة التحضير مصر كافيه\b', 'مصر كافيه', s)
    s = re.sub(r'^قهوة سريعة التحضير 3 في 1 شوكولاتة نسكافيه', 'نسكافيه 3 في 1 شوكولاتة', s)
    s = re.sub(r'^قهوة سريعة التحضير ريتش اند سموز جولد نسكافيه', 'نسكافيه جولد ريتش آند سموث', s)

    # 3. Indomie / Instant noodles cleanups
    if 'شعرية سريعة التحضير' in s and ('إندومي' in s or 'اندومي' in s):
        s = re.sub(r'^شعرية سريعة التحضير\s*', '', s)
        s = re.sub(r'\s*كيس صغير\s*', ' صغير ', s)
        m = re.match(r'^(?:بطعم\s+)?(.+?)\s+(إندومي|اندومي)\s*(\(.*\)|-.*)?$', s)
        if m:
            flavor = m.group(1).strip()
            flavor = re.sub(r'^بطعم\s+', '', flavor)
            flavor = re.sub(r'^ال', '', flavor)
            suffix = (' ' + m.group(3).strip()) if m.group(3) else ''
            s = f'إندومي {flavor}{suffix}'
        else:
            s = f'إندومي {s}'
            s = re.sub(r'إندومي\s+.*(إندومي|اندومي)', 'إندومي', s)
    elif 'شعرية سريعة التحضير' in s:
        s = re.sub(r'^شعرية سريعة التحضير\s*', 'نودلز ', s)

    # 4. Weight ranges in diapers
    s = re.sub(r'\s*-\s*\d+[\s\-\+]*(?:\d+)?ك\s*-\s*', ' - ', s)

    # 5. Long deodorants / anti-perspirant prefixes
    s = re.sub(r'مزيل رائحة العرق ومزيل عرق رول أون\s*', 'مزيل عرق رول أون ', s)
    s = re.sub(r'مضاد التعرق ومزيل رائحة العرق\s*', 'مزيل عرق ', s)
    s = re.sub(r'مزيل رائحة العرق\s*', 'مزيل عرق ', s)
    s = re.sub(r'مضاد التعرق رول اون\s*', 'مزيل عرق رول أون ', s)
    s = re.sub(r'مضاد التعرق سبراي\s*', 'مزيل عرق سبراي ', s)
    s = re.sub(r'مضاد التعرق ستيك\s*', 'مزيل عرق ستيك ', s)

    # 6. Adult / baby diapers size cleanups
    # Format weights cleanly without dropping them if they distinguish sizes
    s = re.sub(r'\s*-\s*([+\d]+[\s\-\+]*\d*)ك\s*-\s*', r' (\1 كجم) - ', s)
    s = re.sub(r'\s*-\s*(\d+\s*-\s*\d+\s*سم)\s*-\s*', r' (\1) - ', s)
    s = re.sub(r'\s*-\s*(\d+سم وأكثر)\s*-\s*', r' (\1) - ', s)
    s = re.sub(r'حفاضات أطفال\s*', 'حفاضات ', s)
    s = re.sub(r'حفاضات اطفال\s*', 'حفاضات ', s)
    s = re.sub(r'حفاضات كبار سن\s*', 'حفاضات كبار السن ', s)

    # 7. Repetitive words
    s = re.sub(r'طويل جدا جدا', 'طويل جداً', s)

    # 7. Clean punctuation / spacing
    s = re.sub(r'\s*-\s*\)', ')', s)
    s = re.sub(r'\(\s*-\s*', '(', s)
    s = re.sub(r'\(\s*\)', '', s)
    s = re.sub(r'\s{2,}', ' ', s)
    return s.strip()

