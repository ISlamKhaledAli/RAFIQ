#!/usr/bin/env node
/**
 * Rafiq POS - License secrets setup (Audit F-04 / F-05 / F-15)
 *
 * Generates, ONLY on the owner's machine:
 *   - an RSA-2048 key pair for signing license tokens and offline support codes
 *   - fresh random APP_API_KEY and ADMIN_SECRET values
 *
 * Outputs (all git-ignored except the public C# config):
 *   license-server/.secrets/license_private_key.pem   -> keep offline, back it up safely
 *   license-server/.secrets/production.secrets.json   -> upload with: npx wrangler secret bulk .secrets/production.secrets.json
 *   license-server/.dev.vars                          -> local `wrangler dev` only
 *   desktop/Common/LicenseConfig.cs                   -> PUBLIC key + client id compiled into the desktop app
 *
 * Usage:
 *   node scripts/setup-secrets.mjs            (creates keys only if they do not exist yet)
 *   node scripts/setup-secrets.mjs --rotate   (replaces all keys; every shop must re-activate once)
 */
import { generateKeyPairSync, randomBytes, createPrivateKey, createPublicKey } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync, chmodSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const serverDir = resolve(here, '..');
const repoDir = resolve(serverDir, '..');
const secretsDir = join(serverDir, '.secrets');
const privateKeyPath = join(secretsDir, 'license_private_key.pem');
const bulkPath = join(secretsDir, 'production.secrets.json');
const devVarsPath = join(serverDir, '.dev.vars');
const csConfigPath = join(repoDir, 'desktop', 'Common', 'LicenseConfig.cs');

const rotate = process.argv.includes('--rotate');
mkdirSync(secretsDir, { recursive: true });

let privateKeyPem;
let secrets;
if (!rotate && existsSync(privateKeyPath) && existsSync(bulkPath)) {
  privateKeyPem = readFileSync(privateKeyPath, 'utf8');
  secrets = JSON.parse(readFileSync(bulkPath, 'utf8'));
  console.log('Existing keys found - reusing them (pass --rotate to replace).');
} else {
  const { privateKey } = generateKeyPairSync('rsa', { modulusLength: 2048, publicExponent: 0x10001 });
  privateKeyPem = privateKey.export({ type: 'pkcs8', format: 'pem' }).toString();
  secrets = {
    APP_API_KEY: randomBytes(32).toString('hex'),
    ADMIN_SECRET: randomBytes(32).toString('hex'),
    LICENSE_PRIVATE_KEY: privateKeyPem,
  };
  writeFileSync(privateKeyPath, privateKeyPem, { mode: 0o600 });
  writeFileSync(bulkPath, JSON.stringify(secrets, null, 2), { mode: 0o600 });
  console.log(rotate ? 'Keys ROTATED.' : 'New keys generated.');
}
try { chmodSync(privateKeyPath, 0o600); chmodSync(bulkPath, 0o600); } catch { /* Windows */ }

// Local development variables for `wrangler dev` (Wrangler reads .dev.vars automatically)
const devVars = [
  `APP_API_KEY="${secrets.APP_API_KEY}"`,
  `ADMIN_SECRET="${secrets.ADMIN_SECRET}"`,
  `LICENSE_PRIVATE_KEY="${secrets.LICENSE_PRIVATE_KEY.replace(/\n/g, '\\n')}"`,
  '',
].join('\n');
writeFileSync(devVarsPath, devVars, { mode: 0o600 });

// Public key in the XML format understood by .NET Framework RSACryptoServiceProvider.FromXmlString
const jwk = createPublicKey(createPrivateKey(privateKeyPem)).export({ format: 'jwk' });
const toB64 = (b64url) => Buffer.from(b64url, 'base64url').toString('base64');
const publicKeyXml = `<RSAKeyValue><Modulus>${toB64(jwk.n)}</Modulus><Exponent>${toB64(jwk.e)}</Exponent></RSAKeyValue>`;

const cs = `// <auto-generated>
// Generated by license-server/scripts/setup-secrets.mjs - do not edit by hand.
// Contains only PUBLIC values: the RSA public key can verify licenses but cannot create them.
// The client API key only identifies the app to the license server; it is not a security boundary.
// </auto-generated>
namespace RafiqPOS.Common
{
    public static class LicenseConfig
    {
        public const string CLIENT_API_KEY = "${secrets.APP_API_KEY}";

        public const string LICENSE_PUBLIC_KEY_XML = "${publicKeyXml}";
    }
}
`;
writeFileSync(csConfigPath, cs);

console.log('\nWritten:');
console.log('  ' + privateKeyPath + '   (PRIVATE - back up offline, never commit)');
console.log('  ' + bulkPath + '   (PRIVATE - upload then keep offline)');
console.log('  ' + devVarsPath + '   (PRIVATE - local wrangler dev)');
console.log('  ' + csConfigPath + '   (public - commit and rebuild the desktop app)');
console.log('\nNext: cd license-server && npx wrangler secret bulk .secrets/production.secrets.json && npx wrangler deploy');
