import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { parseScaleBarcode } from '../src/utils/scaleBarcode.ts';
import { cleanExcelBarcode } from '../src/utils/barcodeReader.ts';

describe('Senior Edge Cases & Scale Audit Tests (فحص السنيور للميزان والإكسل والأرباح)', () => {

  describe('1. Electronic Scale Barcode Parser (باركود الميزان الإلكتروني GS1 20/21/22)', () => {
    it('accurately parses standard 13-digit scale barcode with prefix 21 and weight 1.250 kg', () => {
      // 21 (prefix) + 00045 (PLU 45) + 01250 (1250g) + 3 (check digit) = 13 digits
      const raw = '2100045012503';
      const parsed = parseScaleBarcode(raw);
      
      assert.ok(parsed !== null, 'Scale barcode should be recognized');
      assert.equal(parsed.isScaleBarcode, true);
      assert.equal(parsed.prefix, '21');
      assert.equal(parsed.itemPlu, '00045');
      assert.equal(parsed.itemPluTrimmed, '45');
      assert.equal(parsed.weightGrams, 1250);
      assert.equal(parsed.weightMilli, 1250); // 1,250 milli = 1.250 kg
      assert.equal(parsed.weightKg, 1.25);
    });

    it('accurately parses scale barcode with prefix 20 and fractional weight 0.375 kg (375 grams)', () => {
      // 20 (prefix) + 00128 (PLU 128) + 00375 (375g) + 9 (check digit) = 13 digits
      const raw = '2000128003759';
      const parsed = parseScaleBarcode(raw);
      
      assert.ok(parsed !== null);
      assert.equal(parsed.prefix, '20');
      assert.equal(parsed.itemPluTrimmed, '128');
      assert.equal(parsed.weightGrams, 375);
      assert.equal(parsed.weightMilli, 375);
      assert.equal(parsed.weightKg, 0.375);
    });

    it('accurately parses scale barcode with prefix 22', () => {
      // 22 (prefix) + 05001 (PLU 5001) + 02500 (2500g = 2.5kg) + 0
      const raw = '2205001025000';
      const parsed = parseScaleBarcode(raw);
      
      assert.ok(parsed !== null);
      assert.equal(parsed.prefix, '22');
      assert.equal(parsed.itemPluTrimmed, '5001');
      assert.equal(parsed.weightGrams, 2500);
      assert.equal(parsed.weightMilli, 2500);
      assert.equal(parsed.weightKg, 2.5);
    });

    it('rejects regular manufacturer barcodes that do not start with scale prefixes (e.g. Egypt 622, USA 012)', () => {
      assert.equal(parseScaleBarcode('6223001234567'), null, 'Egyptian manufacturer barcode 622 is not a scale barcode');
      assert.equal(parseScaleBarcode('4006381333931'), null, 'German barcode 400 is not a scale barcode');
      assert.equal(parseScaleBarcode('2000000000015'), null, 'Internal store sequence barcode (prefix 200) with 0 weight is not a scale barcode');
    });

    it('rejects invalid or malformed barcodes', () => {
      assert.equal(parseScaleBarcode(''), null);
      assert.equal(parseScaleBarcode('2100045'), null, 'Too short');
      assert.equal(parseScaleBarcode('210004501250399'), null, 'Too long');
      assert.equal(parseScaleBarcode('2100045ABCD03'), null, 'Contains letters');
      assert.equal(parseScaleBarcode('2100045000000'), null, 'Zero weight is invalid');
    });
  });

  describe('2. Excel Barcode Cleansing & Zero Preservation (استيراد الإكسل والباركود)', () => {
    it('converts scientific notation produced by Excel back to full numeric barcode string', () => {
      // Excel often formats 13-digit EANs as e.g. 6.223001234567E+12
      const rawSci = '6.223001234567E+12';
      const cleaned = cleanExcelBarcode(rawSci);
      assert.equal(cleaned, '6223001234567');
    });

    it('strips float decimal .0 generated by Excel number formatting', () => {
      const rawFloat = '6221044001234.0';
      const cleaned = cleanExcelBarcode(rawFloat);
      assert.equal(cleaned, '6221044001234');
    });

    it('preserves leading zeros on alphanumeric or text barcodes', () => {
      const rawLeadingZero = '0123456789';
      const cleaned = cleanExcelBarcode(rawLeadingZero);
      assert.equal(cleaned, '0123456789');
    });

    it('converts Arabic / Indic numerals to standard ASCII digits', () => {
      const rawArabic = '٦٢٢٣٠٠١٢٣٤٥٦٧';
      const cleaned = cleanExcelBarcode(rawArabic);
      assert.equal(cleaned, '6223001234567');
    });
  });

  describe('3. Net Operating Profit Equation Invariants (حساب صافي الأرباح التشغيلية)', () => {
    it('strictly subtracts operating expenses from net profit calculation', () => {
      const salesGrossProfitPiasters = 150000;   // 1,500.00 EGP gross profit
      const todayExpensesPiasters = 45000;       // 450.00 EGP operating expenses (rent, tea, maintenance)
      const inventoryLossPiasters = 5000;        // 50.00 EGP damaged stock
      const inventorySurplusPiasters = 2000;     // 20.00 EGP audit surplus
      const epayNetProfitPiasters = 3000;        // 30.00 EGP Fawry commissions

      // Net Operating Profit = Gross Profit - Operating Expenses - Inventory Losses + Inventory Surpluses + Epay Profit
      const netProfitPiasters = salesGrossProfitPiasters 
        - todayExpensesPiasters 
        - inventoryLossPiasters 
        + inventorySurplusPiasters 
        + epayNetProfitPiasters;

      assert.equal(netProfitPiasters, 105000); // 1,050.00 EGP
      assert.ok(netProfitPiasters < salesGrossProfitPiasters, 'Net profit must be less than gross profit when expenses exist');
    });

    it('detects negative net profit (net loss) when expenses exceed sales profit', () => {
      const salesGrossProfitPiasters = 20000;    // 200.00 EGP
      const todayExpensesPiasters = 35000;       // 350.00 EGP

      const netProfitPiasters = salesGrossProfitPiasters - todayExpensesPiasters;
      assert.equal(netProfitPiasters, -15000); // Net loss of 150.00 EGP
      assert.ok(netProfitPiasters < 0);
    });
  });

  describe('4. FEFO Expiry Sorting & Batch Invariants', () => {
    it('ensures batches with null or empty expiry dates are pushed after batches with real expiry dates', () => {
      const batches = [
        { id: 'b1', expiry_date: null, created_at: '2026-01-01' },
        { id: 'b2', expiry_date: '', created_at: '2026-01-02' },
        { id: 'b3', expiry_date: '2026-06-30', created_at: '2026-02-01' },
        { id: 'b4', expiry_date: '2026-03-15', created_at: '2026-02-05' },
      ];

      // Replicating SQL:
      // ORDER BY CASE WHEN expiry_date IS NULL OR expiry_date = '' THEN 1 ELSE 0 END ASC, expiry_date ASC, created_at ASC
      const sorted = [...batches].sort((a, b) => {
        const aEmpty = !a.expiry_date || a.expiry_date.trim() === '';
        const bEmpty = !b.expiry_date || b.expiry_date.trim() === '';
        if (aEmpty !== bEmpty) return aEmpty ? 1 : -1;
        if (!aEmpty && !bEmpty && a.expiry_date !== b.expiry_date) {
          return a.expiry_date.localeCompare(b.expiry_date);
        }
        return a.created_at.localeCompare(b.created_at);
      });

      assert.equal(sorted[0].id, 'b4', 'Earliest expiry date (2026-03-15) must come first');
      assert.equal(sorted[1].id, 'b3', 'Second earliest expiry date (2026-06-30) must come second');
      assert.equal(sorted[2].id, 'b1', 'Unassigned expiry dates must come last');
      assert.equal(sorted[3].id, 'b2', 'Empty string expiry dates must come last');
    });
  });
});
