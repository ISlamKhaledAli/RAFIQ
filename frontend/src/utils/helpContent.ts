export function normalizeHelpText(value: string): string {
  return value
    .toLowerCase()
    .replace(/[\u064B-\u065F\u0670\u0640]/g, '')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/[٠-٩]/g, (d) => String('٠١٢٣٤٥٦٧٨٩'.indexOf(d)))
    .replace(/\s+/g, ' ')
    .trim();
}

export interface HelpSearchResult {
  articles: { article: HelpArticle; matchedSteps: HelpGuideStep[] }[];
  faqs: FaqItem[];
}

const stepText = (s: HelpGuideStep): string => normalizeHelpText(`${s.title} ${s.description} ${s.shortcut ?? ''}`);
const articleText = (a: HelpArticle): string =>
  normalizeHelpText(`${a.title} ${a.summary} ${a.keywords.join(' ')} ${a.goldenRule} ${a.troubleshooting ?? ''}`) + ' ' + a.steps.map(stepText).join(' ');
const faqText = (f: FaqItem): string => normalizeHelpText(`${f.question} ${f.answer} ${f.category} ${f.tag}`);

/** Every word of the query must appear (Arabic spelling variants and Arabic digits are normalised). */
export function searchHelp(query: string, articles: readonly HelpArticle[], faqs: readonly FaqItem[]): HelpSearchResult {
  const tokens = normalizeHelpText(query).split(' ').filter(Boolean);
  if (tokens.length === 0) return { articles: articles.map((article) => ({ article, matchedSteps: [] })), faqs: [...faqs] };
  const hitsAll = (haystack: string) => tokens.every((t) => haystack.includes(t));
  return {
    articles: articles
      .filter((a) => hitsAll(articleText(a)))
      .map((article) => ({ article, matchedSteps: article.steps.filter((s) => hitsAll(stepText(s))) })),
    faqs: faqs.filter((f) => hitsAll(faqText(f)))
  };
}

// Any one of these permissions opens the guide; admins and owners see every guide.
const SECTION_PERMISSIONS: Record<HelpArticleSectionId, readonly string[]> = {
  pos: ['pos.access', 'pos'],
  payment: ['pos.access', 'pos'],
  sales: ['invoices.view', 'returns.create'],
  customers: ['customers.view', 'customers'],
  products: ['products.view', 'products'],
  purchases: ['purchases.view', 'shortage.view', 'suppliers.manage'],
  wallets: ['wallets.access', 'wallets', 'epay.access', 'epay'],
  shifts: ['reports.sales', 'reports', 'shifts.view', 'shifts.open', 'reports.daily_closing'],
  printing: ['pos.access', 'pos', 'settings.printer', 'settings.barcode'],
  backup_security: ['settings.backup', 'settings.store', 'settings', 'users.view']
};

export function isHelpSectionAllowed(sectionId: HelpSectionId, isAdmin: boolean, hasPermission: (key: string) => boolean): boolean {
  if (sectionId === 'faq' || sectionId === 'support') return true;
  if (isAdmin) return true;
  return SECTION_PERMISSIONS[sectionId].some((key) => hasPermission(key));
}

const HELP_SECTION_ALIASES: Readonly<Record<string, HelpSectionId>> = {
  settings: 'backup_security',
  dashboard: 'shifts',
  epay: 'wallets'
};

const HELP_SECTION_ORDER: readonly HelpSectionId[] = [
  'pos', 'payment', 'sales', 'customers', 'products', 'purchases', 'wallets', 'shifts', 'printing', 'backup_security', 'faq', 'support'
];

/** The guide to open for a requested section id (screen names map to their guide); falls back to the first guide the user may read. */
export function resolveHelpSection(requested: string | undefined, isAllowed: (id: HelpSectionId) => boolean): HelpSectionId {
  const wanted = (HELP_SECTION_ORDER as readonly string[]).includes(requested ?? '')
    ? (requested as HelpSectionId)
    : HELP_SECTION_ALIASES[requested ?? ''] ?? 'pos';
  if (isAllowed(wanted)) return wanted;
  return HELP_SECTION_ORDER.find((id) => isAllowed(id)) ?? 'faq';
}
